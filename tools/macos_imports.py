#!/usr/bin/env python3
"""Generate the macOS guest image's host import stubs.

As on Android (tools/android_imports.py), every function the guest imports
from the host (port/macos/host_imports.list, and the posix_*.c helpers
through the generated hostposix_ list) gets a stub that loads the host's
64-bit function address from __host_import_table and branches to it.

The macOS guest runs in a window of the host's address space
(tools/macos_asm_rebase.py): guest address A is host address window + A,
the window's base in x28. So the stub also turns each pointer the guest
passes into the host address it stands for, from the function's prototype
in the headers given with --prototypes: the host then takes ordinary
pointers, and the posix_*.c files run there as they are. A null pointer
stays null. The arguments go in x0 to x7 (and v0 to v7 for floating point):
a pointer passed on the stack, a structure passed by value or a variadic
function stops the generation, as does a name without a prototype.

`void *` parameters that are handles, not memory (the posix_directory_*
functions'), are listed in HANDLES. Return values pass through as they are:
the host returns guest addresses or handles, never its own pointers.

Usage: macos_imports.py [--host-table table.c] --prototypes header... output.s list...
"""

import re
import sys

# parameters (by index) of type void * that carry handles
HANDLES = {
    "posix_directory_next": {0},
    "posix_directory_close": {0},
}

FLOAT_TYPES = {"float", "double", "FLOAT"}


class ImportError_(Exception):
    pass


def parse_prototypes(paths):
    prototypes = {}
    for path in paths:
        text = open(path, encoding="utf-8").read()
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        text = re.sub(r"//[^\n]*", "", text)
        text = re.sub(r"\\\n", " ", text)
        text = re.sub(r"^\s*#[^\n]*", "", text, flags=re.M)
        for m in re.finditer(r"([A-Za-z_][\w \*]*?)\b(\w+)\s*\(([^;{}()]*(?:\([^)]*\)[^;{}()]*)*)\)\s*"
                             r"(?:__attribute__\s*\(\([^;]*\)\))?\s*;", text):
            ret, name, params = m.group(1), m.group(2), m.group(3)
            if name in ("if", "while", "for", "return", "sizeof"):
                continue
            prototypes[name] = (" ".join(ret.split()), " ".join(params.split()))
    return prototypes


def classify(name, params):
    """the pointer arguments' registers (x0 to x7), in a list"""
    if params in ("", "void"):
        return []
    pointers = []
    gpr = 0
    for index, param in enumerate(p.strip() for p in params.split(",")):
        if param == "...":
            raise ImportError_(f"{name} is variadic")
        if "(" in param:
            raise ImportError_(f"{name} takes a function pointer: pass it as an unsigned int")
        words = param.replace("*", " * ").split()
        is_pointer = "*" in words
        base_type = [w for w in words if w not in ("const", "volatile", "unsigned", "signed", "struct", "*")]
        if not is_pointer and base_type and base_type[0] in FLOAT_TYPES:
            continue
        if not is_pointer and base_type and base_type[0].startswith(("struct", "union")):
            raise ImportError_(f"{name} takes a structure by value")
        if is_pointer and index in HANDLES.get(name, set()):
            is_pointer = False
        if is_pointer:
            if gpr >= 8:
                raise ImportError_(f"{name} passes a pointer on the stack")
            pointers.append(gpr)
        gpr += 1
    return pointers


def main():
    arguments = sys.argv[1:]
    host_table = None
    headers = []
    while arguments and arguments[0].startswith("--"):
        if arguments[0] == "--host-table":
            host_table = arguments[1]
        elif arguments[0] == "--prototypes":
            headers.append(arguments[1])
        else:
            sys.exit(f"unknown option {arguments[0]}")
        arguments = arguments[2:]
    output, lists = arguments[0], arguments[1:]
    names = []
    for path in lists:
        for line in open(path, encoding="utf-8"):
            line = line.split("#", 1)[0].strip()
            if line and line not in names:
                names.append(line)
    prototypes = parse_prototypes(headers)

    def symbol(n):
        # hostposix_<name> imports port/linux/src/posix.h's posix_<name>
        return "posix_" + n[len("hostposix_"):] if n.startswith("hostposix_") else n

    out = ["/* generated by tools/macos_imports.py; do not edit */", "\t.text"]
    errors = []
    for index, name in enumerate(names):
        prototype = prototypes.get(symbol(name))
        if not prototype:
            errors.append(f"{name}: no prototype in {', '.join(headers)}")
            continue
        try:
            pointers = classify(symbol(name), prototype[1])
        except ImportError_ as error:
            errors.append(str(error))
            continue
        offset = index * 8
        out += [
            f"\t.globl {name}",
            f"\t.type {name},%function",
            "\t.p2align 2",
            f"{name}:",
        ]
        for register in pointers:
            out += [
                f"\tcbz w{register}, .L{name}_{register}",
                f"\tadd x{register}, x28, w{register}, uxtw",
                f".L{name}_{register}:",
            ]
        out += [
            f"\tadrp x16, __host_import_table+{offset}",
            f"\tldr x16, [x16, :lo12:__host_import_table+{offset}]",
            "\tbr x16",
        ]
    if errors:
        sys.exit("\n".join(errors))
    out += [
        "\t.section .rodata",
        "\t.globl __host_import_names",
        "__host_import_names:",
    ]
    out += [f'\t.asciz "{name}"' for name in names]
    out += [
        "\t.p2align 2",
        "\t.globl __host_import_count",
        "__host_import_count:",
        f"\t.long {len(names)}",
        "\t.data",
        "\t.p2align 3",
        "\t.globl __host_import_table",
        "__host_import_table:",
        f"\t.zero {max(len(names), 1) * 8}",
    ]
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    if host_table:
        table = ["/* generated by tools/macos_imports.py; do not edit */",
                 "#include <string.h>", ""]
        table += [f"extern void {symbol(n)}(void);" for n in names]
        table += ["", "static const struct { const char *name; void *function; } imports[] =", "{"]
        table += [f'\t{{ "{n}", (void *){symbol(n)} }},' for n in names]
        table += ["};", "",
                  "void *host_resolve_import(const char *name)",
                  "{",
                  "\tunsigned long index;",
                  "",
                  "\tfor (index = 0; index < sizeof(imports) / sizeof(imports[0]); index++)",
                  "\t{",
                  "\t\tif (!strcmp(imports[index].name, name))",
                  "\t\t\treturn imports[index].function;",
                  "\t}",
                  "\treturn NULL;",
                  "}"]
        with open(host_table, "w", encoding="utf-8") as f:
            f.write("\n".join(table) + "\n")


if __name__ == "__main__":
    main()
